"""Base HAR -> JMX converter. Port of OfflineConverter.java (no WSS)."""
from __future__ import annotations
import xml.etree.ElementTree as ET
from urllib.parse import urlparse, parse_qsl
from .har_model import Entry

EXCLUDED_HEADERS = {"host", "content-length", "connection", "accept-encoding", "transfer-encoding",
                    "cookie", "set-cookie"}
SKIP_SUFFIXES = (".png", ".jpg", ".jpeg", ".ico", ".svg", ".gif", ".woff", ".woff2",
                 ".ttf", ".eot", ".css", ".js")


def should_skip(url: str) -> bool:
    u = url.lower()
    if "/static/" in u:
        return True
    return u.split("?")[0].endswith(SKIP_SUFFIXES)


def _sp(parent, name: str, text: str):
    e = ET.SubElement(parent, "stringProp", {"name": name})
    e.text = text
    return e


def _bp(parent, name: str, text: str):
    e = ET.SubElement(parent, "boolProp", {"name": name})
    e.text = text
    return e


def _empty_args() -> ET.Element:
    args = ET.Element("elementProp", {"name": "HTTPsampler.Arguments", "elementType": "Arguments"})
    ET.SubElement(args, "collectionProp", {"name": "Arguments.arguments"})
    return args


def _query_args(query: str) -> ET.Element:
    args = ET.Element("elementProp", {"name": "HTTPsampler.Arguments", "elementType": "Arguments"})
    coll = ET.SubElement(args, "collectionProp", {"name": "Arguments.arguments"})
    for k, v in parse_qsl(query, keep_blank_values=True):
        a = ET.SubElement(coll, "elementProp", {"name": k, "elementType": "HTTPArgument"})
        _bp(a, "HTTPArgument.always_encode", "true")
        _sp(a, "Argument.name", k)
        _sp(a, "Argument.value", v)
        _sp(a, "Argument.metadata", "=")
        _bp(a, "HTTPArgument.use_equals", "true")
    return args


def _body_args(body: str) -> ET.Element:
    args = ET.Element("elementProp", {"name": "HTTPsampler.Arguments", "elementType": "Arguments"})
    coll = ET.SubElement(args, "collectionProp", {"name": "Arguments.arguments"})
    a = ET.SubElement(coll, "elementProp", {"name": "", "elementType": "HTTPArgument"})
    _bp(a, "HTTPArgument.always_encode", "false")
    _sp(a, "Argument.value", body)
    _sp(a, "Argument.metadata", "=")
    _bp(a, "HTTPArgument.use_equals", "true")
    return args


def _header_manager(headers) -> ET.Element | None:
    prop = ET.Element("elementProp", {"name": "HTTPSampler.header_manager",
                                      "elementType": "HeaderManager"})
    coll = ET.SubElement(prop, "collectionProp", {"name": "HeaderManager.headers"})
    n = 0
    for h in headers:
        if not h.name or h.name.lower() in EXCLUDED_HEADERS:
            continue
        hp = ET.SubElement(coll, "elementProp", {"name": h.name, "elementType": "Header"})
        _sp(hp, "Header.name", h.name)
        _sp(hp, "Header.value", h.value)
        n += 1
    return prop if n else None


def _sampler(entry: Entry) -> ET.Element | None:
    url, method = entry.request.url, entry.request.method
    if should_skip(url):
        return None
    s = ET.Element("HTTPSamplerProxy", {"guiclass": "HttpTestSampleGui",
                                        "testclass": "HTTPSamplerProxy",
                                        "testname": url, "enabled": "true"})
    try:
        u = urlparse(url)
        _sp(s, "HTTPSampler.protocol", u.scheme or "http")
        _sp(s, "HTTPSampler.domain", u.hostname or "")
        _sp(s, "HTTPSampler.port", str(u.port) if u.port else "")
        _sp(s, "HTTPSampler.path", u.path or "/")
        s.append(_query_args(u.query) if u.query else _empty_args())
    except Exception:
        _sp(s, "HTTPSampler.path", url)
        s.append(_empty_args())
    _sp(s, "HTTPSampler.method", method)
    _bp(s, "HTTPSampler.follow_redirects", "true")
    _bp(s, "HTTPSampler.auto_redirects", "false")
    _bp(s, "HTTPSampler.use_keepalive", "true")
    _bp(s, "HTTPSampler.DO_MULTIPART_POST", "false")
    if method in ("POST", "PUT", "PATCH") and entry.request.postData is not None:
        _bp(s, "HTTPSampler.postBodyRaw", "true")
        s.append(_body_args(entry.request.postData.text or ""))
    hm = _header_manager(entry.request.headers)
    if hm is not None:
        s.append(hm)
    return s


def _test_plan() -> ET.Element:
    tp = ET.Element("TestPlan", {"guiclass": "TestPlanGui", "testclass": "TestPlan",
                                 "testname": "Test Plan (E2ELoader is helping you)",
                                 "enabled": "true"})
    _sp(tp, "TestPlan.comments", "Generated by e2eloader (OfflineConverter port)")
    _bp(tp, "TestPlan.functional_mode", "false")
    _bp(tp, "TestPlan.serialize_threadgroups", "false")
    args = ET.SubElement(tp, "elementProp",
                         {"name": "TestPlan.user_defined_variables", "elementType": "Arguments",
                          "guiclass": "ArgumentsPanel", "testclass": "Arguments",
                          "testname": "User Defined Variables", "enabled": "true"})
    ET.SubElement(args, "collectionProp", {"name": "Arguments.arguments"})
    return tp


def _thread_group() -> ET.Element:
    tg = ET.Element("ThreadGroup", {"guiclass": "ThreadGroupGui", "testclass": "ThreadGroup",
                                    "testname": "Thread Group", "enabled": "true"})
    _sp(tg, "ThreadGroup.on_sample_error", "continue")
    loop = ET.SubElement(tg, "elementProp",
                         {"name": "ThreadGroup.main_controller", "elementType": "LoopController",
                          "guiclass": "LoopControllerPanel", "testclass": "LoopController",
                          "testname": "Loop Controller", "enabled": "true"})
    _bp(loop, "LoopController.continue_forever", "false")
    _sp(loop, "LoopController.loops", "1")
    _sp(tg, "ThreadGroup.num_threads", "1")
    _sp(tg, "ThreadGroup.ramp_time", "1")
    _bp(tg, "ThreadGroup.scheduler", "false")
    _sp(tg, "ThreadGroup.duration", "")
    _sp(tg, "ThreadGroup.delay", "")
    return tg


def build_base_doc(entries: list[Entry]) -> ET.ElementTree:
    root = ET.Element("jmeterTestPlan", {"version": "1.2", "properties": "5.0",
                                         "jmeter": "5.4.3"})
    ht = ET.SubElement(root, "hashTree")
    ht.append(_test_plan())
    tht = ET.SubElement(ht, "hashTree")
    tht.append(_thread_group())
    ght = ET.SubElement(tht, "hashTree")
    hm = ET.Element("HeaderManager", {"guiclass": "HeaderPanel", "testclass": "HeaderManager",
                                      "testname": "HTTP Header Manager", "enabled": "true"})
    ET.SubElement(hm, "collectionProp", {"name": "HeaderManager.headers"})
    ght.append(hm)
    ET.SubElement(ght, "hashTree")
    for e in entries:
        if (e.request.url or "").lower().startswith(("ws://", "wss://")):
            continue  # WSS out of scope
        s = _sampler(e)
        if s is None:
            continue
        ght.append(s)
        ET.SubElement(ght, "hashTree")
    return ET.ElementTree(root)


def write_xml(tree: ET.ElementTree, path: str) -> None:
    import os
    os.makedirs(os.path.dirname(os.path.abspath(path)) or ".", exist_ok=True)
    try:
        ET.indent(tree, space="  ")
    except Exception:
        pass
    tree.write(path, encoding="utf-8", xml_declaration=True)
